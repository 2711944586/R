.se_prose <- function(...) {
  parts <- c(...)
  if (!length(parts)) return("")
  body <- paste0("<p>", parts, "</p>", collapse = "\n")
  sprintf("<div class='method-block'>%s</div>", body)
}

.se_code <- function(code_text, title = "\u8865\u5145\u5206\u6790\u4ee3\u7801") {
  if (exists(".ghs_code", mode = "function")) {
    .ghs_code(code_text, "r", title)
  } else {
    paste0("<pre class='code-block'><code class='language-r'>",
           code_text, "</code></pre>")
  }
}

.se_fig_grid <- function(fig_dir, figs, ncol = 3) {
  items <- paste0(vapply(figs, function(f) {
    path <- file.path(fig_dir, f[[1]])
    if (exists(".ghs_fig", mode = "function")) {
      .ghs_fig(path, f[[2]], f[[3]])
    } else {
      if (!file.exists(path)) return("")
      sprintf("<figure><img src='%s' alt='%s'/><figcaption>%s</figcaption></figure>",
              path, f[[2]], f[[3]])
    }
  }, character(1)), collapse = "\n")
  items
}

.se_widget_grid <- function(widget_dir, widgets, mode, repo_url) {
  items <- paste0(vapply(widgets, function(w) {
    if (exists(".ghs_widget_anchor", mode = "function")) {
      .ghs_widget_anchor(widget_dir, w[[1]], w[[2]], mode, repo_url)
    } else {
      path <- file.path(widget_dir, w[[1]])
      if (!file.exists(path)) return("")
      sprintf("<iframe src='%s' title='%s' class='widget-embed'></iframe>",
              path, w[[2]])
    }
  }, character(1)), collapse = "\n")
  items
}

.se_block <- function(fig_dir, widget_dir, mode, repo_url,
                      prose_before, figs, code, widgets, prose_after) {
  paste0(
